// Refresh the seasonal event places from buddy.farm and write data/event-places.js.
//
//   node tools/build-event-places.mjs
//
// buddy.farm publishes the community drop logs for every place, events
// included, as "explores (or casts) per drop". data/data.js was built before
// Apple Bobbing existed and carries older counts for the other two, so this
// file replaces their drop tables at load time and adds the missing one.
//
// The raw pages are kept in raw/buddy-events-<date>.json so the numbers can be
// traced back to where they came from.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BUDDY = "https://buddy.farm";
// buddy.farm does not flag events, so they are named here.
const EVENTS = [
  { slug: "haunted-house", name: "Haunted House", season: "Halloween" },
  { slug: "santa-s-workshop", name: "Santa's Workshop", season: "Christmas" },
  { slug: "apple-bobbing", name: "Apple Bobbing", season: "Apple Bobbing event" },
];

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.json();
}

const table = (variant) => {
  const out = {};
  for (const row of (variant && variant.items) || []) {
    const rate = Number(row.rate);
    if (row.item && row.item.name && rate > 0) out[row.item.name] = { denom: rate, src: "logged" };
  }
  return out;
};

const pages = {};
const places = [];
const ironDepot = {};
for (const event of EVENTS) {
  const data = await getJson(`${BUDDY}/page-data/l/${event.slug}/page-data.json`);
  pages[event.slug] = data;
  const loc = ((data.result.data.farmrpg || {}).locations || [])[0];
  if (!loc) throw new Error(`no location on ${event.slug}`);
  const variants = loc.dropRates || [];
  if (loc.type === "fishing") {
    const nets = variants.find((v) => v.manualFishing === false && !v.runecube);
    const rod = variants.find((v) => v.manualFishing === true && !v.runecube);
    places.push({ name: event.name, type: "fishing", mode: "fishes", event: true, season: event.season, drops: table(nets), fish: table(rod) });
  } else {
    const plain = variants.find((v) => !v.ironDepot && !v.runecube);
    const depot = variants.find((v) => v.ironDepot && !v.runecube);
    places.push({ name: event.name, type: "explore", mode: "explores", event: true, season: event.season, drops: table(plain), fish: {} });
    if (depot) ironDepot[event.name] = Object.fromEntries(Object.entries(table(depot)).map(([k, v]) => [k, v.denom]));
  }
}

const date = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(root, "raw", `buddy-events-${date}.json`), JSON.stringify({ source: BUDDY, fetched: date, pages }));

const body = `// Seasonal event places, from buddy.farm's community drop logs (${date}).
// Generated by tools/build-event-places.mjs - do not hand-edit.
// Unit: explores (or casts) per drop, the same as data/data.js.
// Replaces the older tables data.js carries for these places and adds any it
// lacks. Load after data/data.js, data/extra-items.js and data/location-rates.js.
(function () {
  var EVENTS = ${JSON.stringify(places)};
  var DEPOT = ${JSON.stringify(ironDepot)};
  var D = window.FRPG_DATA;
  if (!D || !D.sources || !Array.isArray(D.sources.locations)) return;
  EVENTS.forEach(function (place) {
    var list = D.sources.locations;
    var at = list.findIndex(function (loc) { return loc.name === place.name && loc.type === place.type; });
    if (at >= 0) list[at] = Object.assign({}, list[at], place);
    else list.push(place);
  });
  var rates = window.FRPG_LOCATION_RATES;
  if (rates && rates.ironDepot) Object.keys(DEPOT).forEach(function (name) { rates.ironDepot[name] = DEPOT[name]; });
  window.FRPG_EVENT_PLACES = EVENTS.map(function (place) { return { name: place.name, type: place.type, season: place.season }; });
})();
`;
fs.writeFileSync(path.join(root, "data", "event-places.js"), body);
console.log(`wrote data/event-places.js: ${places.map((p) => `${p.name} (${Object.keys(p.drops).length} drops)`).join(", ")}`);
