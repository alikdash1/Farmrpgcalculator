// Builds data/item-info.js: the game's own description for every item, plus
// the Buddy's Almanac address for it.
//
//   node tools/build-item-info.mjs
//
// Descriptions come from raw/items-etl2.json (the 2026-07 item export) and,
// for everything added since, from the Buddy capture that data/extra-items.js
// was built from. Slugs come from Buddy's own search index where we have it,
// so links never guess at punctuation ("Re'taw Pail" is /i/re-taw-pail/).
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const readJson = (file) => JSON.parse(read(file));

const clean = (text) => String(text || "")
  .replace(/<br\s*\/?>/gi, " · ")
  .replace(/<[^>]+>/g, "")
  .replace(/\s*·\s*·\s*/g, " · ")
  .replace(/\s+/g, " ")
  .replace(/^[\s·]+|[\s·]+$/g, "")
  .trim();

const context = {};
context.window = context;
vm.createContext(context);
for (const file of ["data/data.js", "data/extra-items.js"]) vm.runInContext(read(file), context, { filename: file });
const items = context.FRPG_DATA.items.items;

const descriptions = new Map();
for (const row of readJson("raw/items-etl2.json").items || []) {
  const key = String(row.name || "").toLowerCase();
  if (key) descriptions.set(key, { d: clean(row.description), x: clean(row.description_ext) });
}
const buddyPages = readJson("raw/buddy-items-2026-09-11.json").pages;
for (const page of Object.values(buddyPages)) {
  const row = (page.items || [])[0];
  if (!row) continue;
  const key = row.name.toLowerCase();
  if (!descriptions.has(key) || !descriptions.get(key).d) descriptions.set(key, { d: clean(row.description), x: "" });
}

// Buddy's own hrefs beat any slug rule we could invent.
const slugs = new Map();
for (const file of ["raw/.buddy-cache-2026-09-11/search.json", "raw/buddy-search-2026-08-31.json"]) {
  let rows;
  try { rows = readJson(file); } catch (_) { continue; }
  for (const entry of rows) {
    const href = String(entry.href || "");
    if (!/^\/i\//.test(href)) continue;
    const key = String(entry.name || "").toLowerCase();
    if (key && !slugs.has(key)) slugs.set(key, href.split("/").filter(Boolean).pop());
  }
}
const slugFor = (name) => slugs.get(name.toLowerCase())
  || name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const info = {};
let described = 0;
for (const item of items) {
  const found = descriptions.get(item.name.toLowerCase()) || { d: "", x: "" };
  const entry = { slug: slugFor(item.name) };
  if (found.d) { entry.desc = found.d; described += 1; }
  if (found.x && found.x !== found.d) entry.note = found.x;
  info[item.name] = entry;
}

const lines = Object.entries(info)
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([name, entry]) => `  ${JSON.stringify(name)}: ${JSON.stringify(entry)}`)
  .join(",\n");
const out = `// Generated by tools/build-item-info.mjs. Do not edit by hand.
//
// What each item says about itself in game, and where it lives on Buddy's
// Almanac. Descriptions: raw/items-etl2.json, with the Buddy capture filling in
// everything added since. ${described} of ${items.length} items have one.
window.FRPG_ITEM_INFO = {
  meta: ${JSON.stringify({ built: new Date().toISOString().slice(0, 10), items: items.length, described, sources: ["items-etl2", "buddy.farm"] })},
  items: {
${lines}
  }
};
`;
fs.writeFileSync(path.join(root, "data", "item-info.js"), out);
console.log(`data/item-info.js: ${items.length} items, ${described} with a description`);
