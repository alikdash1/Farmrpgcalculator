// Find drops our tables carry that are not normal drops, and write data/event-drops.js.
//
//   node tools/build-event-drops.mjs
//
// data/data.js was built from community drop logs, and those logs were taken
// all year - so a few event items logged during an event (painted eggs, heart
// necklace pieces, snowballs) sit in ordinary places' tables as if they always
// drop there. buddy.farm's current table for each place does not list them.
// Every (place, item) we have that buddy's current table lacks is written out
// here, and data/event-drops.js takes it out of the tables at load time, so
// Calculate, Places and Trips never count it. Event places themselves
// (data/event-places.js) are left alone.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BUDDY = "https://buddy.farm";
const getJson = async (url) => { const res = await fetch(url); if (!res.ok) throw new Error(`${url}: ${res.status}`); return res.json(); };

const ctx = {}; ctx.window = ctx; vm.createContext(ctx);
for (const f of ["data/data.js", "data/extra-items.js"]) vm.runInContext(fs.readFileSync(path.join(root, f), "utf8"), ctx, { filename: f });
vm.runInContext(fs.readFileSync(path.join(root, "data/event-places.js"), "utf8"), ctx);
const eventPlaces = new Set((ctx.FRPG_EVENT_PLACES || []).map((p) => p.name));

const search = await getJson(BUDDY + "/search.json");
const hrefByName = new Map(search.filter((e) => /^\/l\//.test(e.href || "")).map((e) => [e.name, e.href]));
const pages = {};
const drops = {};
for (const loc of ctx.FRPG_DATA.sources.locations) {
  if (eventPlaces.has(loc.name)) continue;
  // buddy calls the exploring side of the swamp "Sinking Swamp Exploring".
  const href = hrefByName.get(loc.type === "explore" && loc.name === "Sinking Swamp" ? "Sinking Swamp Exploring" : loc.name);
  if (!href) throw new Error(`${loc.name} is not on buddy.farm`);
  pages[href] ||= (await getJson(`${BUDDY}/page-data${href}page-data.json`)).result.data.farmrpg.locations[0];
  const current = new Set();
  for (const variant of pages[href].dropRates || []) for (const row of variant.items || []) current.add(row.item.name);
  for (const name of new Set([...Object.keys(loc.drops || {}), ...Object.keys(loc.fish || {})])) {
    if (!current.has(name)) (drops[name] ||= []).push({ place: loc.name, type: loc.type });
  }
}

const date = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(root, "raw", `buddy-places-${date}.json`), JSON.stringify({ source: BUDDY, fetched: date, pages }));
const body = `// Drops logged during an event, not normal drops - taken out of the ordinary
// places' tables at load time. Generated by tools/build-event-drops.mjs from
// buddy.farm's current place tables (${date}) - do not hand-edit.
// Load after data/data.js, data/extra-items.js and data/event-places.js.
(function () {
  var DROPS = ${JSON.stringify(drops)};
  window.FRPG_EVENT_DROPS = DROPS;
  var D = window.FRPG_DATA;
  if (!D || !D.sources || !Array.isArray(D.sources.locations)) return;
  Object.keys(DROPS).forEach(function (item) {
    DROPS[item].forEach(function (at) {
      D.sources.locations.forEach(function (loc) {
        if (loc.name !== at.place || loc.type !== at.type) return;
        if (loc.drops) delete loc.drops[item];
        if (loc.fish) delete loc.fish[item];
      });
    });
  });
})();
`;
fs.writeFileSync(path.join(root, "data/event-drops.js"), body);
console.log(`wrote data/event-drops.js: ${Object.keys(drops).length} items`);
for (const [item, at] of Object.entries(drops)) console.log("  " + item + ": " + at.map((a) => a.place).join(", "));
